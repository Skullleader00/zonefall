const { chromium } = require('playwright');
const fs = require('fs');
(async () => {
  const g = '/opt/playwright-browsers/chromium-1209/chrome-linux64/chrome';
  const br = await chromium.launch({ executablePath: fs.existsSync(g) ? g : undefined, args: ['--no-sandbox'] });
  const page = await (await br.newContext({ viewport: { width: 390, height: 844 } })).newPage();
  page.on('pageerror', e => console.log('PE:', e.message.slice(0, 150)));
  page.on('console', m => console.log('C:', m.text().slice(0, 140)));
  await page.goto('http://localhost:3000/index.html'); await page.waitForTimeout(800);
  await page.click('#btnStart'); await page.waitForTimeout(250); await page.click('.rps-btn'); await page.waitForTimeout(1200);
  await page.evaluate(() => { const S = window.__ZF.st(); S.active = 'p0'; S.phase = 'main'; S.turnActions = 0; S.players.p0.flare = 8; S.players.p0.hand = ['sd01001']; window.__ZF.render(); });
  const c = await page.evaluate(() => Z.cardPlayable(window.__ZF.st(), 'p0', 0));
  console.log('playable', JSON.stringify(c).slice(0, 120));
  const b = await page.locator('#hand .gcard').first().boundingBox();
  const t0 = c.cells[0];
  const tp = await page.evaluate(([r, cc]) => { const el = [...document.querySelectorAll('.cell')].find(e => +e.dataset.r === r && +e.dataset.c === cc).getBoundingClientRect(); return [el.x + el.width / 2, el.y + el.height / 2]; }, [t0.r, t0.c]);
  await page.mouse.move(b.x + b.width / 2, b.y + b.height / 2);
  await page.mouse.down();
  await page.mouse.move(b.x + b.width / 2 + 30, b.y + b.height / 2 - 30, { steps: 4 });
  await page.mouse.move(tp[0], tp[1], { steps: 12 });
  await page.mouse.up();
  await page.waitForTimeout(700);
  console.log('after', JSON.stringify(await page.evaluate(() => { const S = window.__ZF.st(); return { hand: S.players.p0.hand.length, tk: document.querySelectorAll('.tk').length, tkimg: !!document.querySelector('.tk .tk-img'), hint: document.getElementById('hint').textContent.slice(0, 50), log: S.log.slice(-1)[0].msg.slice(0, 60) }; })));
  await br.close();
})();
