const { chromium } = require('playwright'); const fs=require('fs');
(async()=>{
const g='/opt/playwright-browsers/chromium-1209/chrome-linux64/chrome';
const br=await chromium.launch({executablePath:fs.existsSync(g)?g:undefined,args:['--no-sandbox']});
const page=await (await br.newContext({viewport:{width:390,height:844}})).newPage();
page.on('pageerror',e=>console.log('PE:',e.message.slice(0,150)));
await page.goto('http://localhost:3000/index.html'); await page.waitForTimeout(800);
await page.click('#btnStart'); await page.waitForTimeout(250); await page.click('.rps-btn'); await page.waitForTimeout(1100);
await page.evaluate(()=>{const S=window.__ZF.st(); S.active='p0'; S.phase='main'; S.turnActions=1; S.players.p0.flare=4;
  Z.deploy(S,'p0',S.players.p0.hand.length-1,{r:4,c:1}); window.__ZF.render();
  const e=document.createElement('div'); e.id='probe'; document.body.appendChild(e);
  window.__probeLog=[];
  const tk=document.querySelector('.tk'); ['pointerdown','pointerup','click','pointermove'].forEach(t=>tk.addEventListener(t,ev=>window.__probeLog.push(t+':'+ev.target.className),true));
});
const b=await page.locator('.tk').first().boundingBox();
await page.mouse.move(b.x+b.width/2,b.y+b.height/2); await page.mouse.down(); await page.waitForTimeout(800);
console.log('during', JSON.stringify(await page.evaluate(()=>({log:window.__probeLog, z:document.getElementById('zoneView').className, title:document.getElementById('zvTitle').textContent.slice(0,20)}))));
await page.mouse.up(); await page.waitForTimeout(300);
console.log('after', JSON.stringify(await page.evaluate(()=>({z:document.getElementById('zoneView').className, title:document.getElementById('zvTitle').textContent.slice(0,20), log:window.__probeLog}))));
await br.close();})();
